    public function run(): void
    {
        $domain = LearningDomain::query()->where('slug', 'driving_license_be')->firstOrFail();
        $categories = LearningCategory::query()
            ->where('learning_domain_id', $domain->id)
            ->get()
            ->keyBy('slug');

        $skills = collect($this->skillDefinitions($categories))
            ->mapWithKeys(function (array $skillData) {
                $skill = Skill::query()->updateOrCreate(
                    ['slug' => $skillData['slug']],
                    array_merge($skillData, [
                        'name_translations' => ['fr' => $skillData['name']],
                        'description_translations' => ['fr' => $skillData['description']],
                        'unlock_level' => $skillData['required_level'],
                        'animation_key' => $this->animationKey($skillData),
                    ]),
                );

                return [$skill->slug => $skill];
            });

        SkillTree::query()->whereIn('slug', [
            'hero-road-tactics',
        ])->delete();

        foreach ($this->treeDefinitions() as $treeData) {
            $tree = SkillTree::query()->updateOrCreate(
                ['slug' => $treeData['slug']],
                [
                    'name' => $treeData['name'],
                    'description' => $treeData['description'],
                    'icon' => $treeData['icon'],
                    'subject_type' => $treeData['subject_type'],
                    'subject_key' => $treeData['subject_key'],
                    'class_slug' => $treeData['class_slug'] ?? null,
                    'role_slug' => $treeData['role_slug'] ?? null,
                    'specialization_slug' => $treeData['specialization_slug'] ?? null,
                ],
            );

            $createdNodes = collect($treeData['nodes'])->mapWithKeys(function (array $nodeData) use ($tree, $skills) {
                $node = SkillNode::query()->updateOrCreate(
                    ['slug' => $nodeData['slug']],
                    [
                        'skill_tree_id' => $tree->id,
                        'skill_id' => $skills[$nodeData['skill']]->id,
                        'column_index' => $nodeData['column'],
                        'row_index' => $nodeData['row'],
                        'unlock_cost' => $nodeData['cost'],
                        'special_cost' => $nodeData['special_cost'],
                        'required_level' => $nodeData['required_level'],
                        'sort_order' => ($nodeData['column'] * 10) + $nodeData['row'],
                        'prerequisite_node_ids' => [],
                    ],
                );

                return [$nodeData['slug'] => $node];
            });

            foreach ($treeData['nodes'] as $nodeData) {
                $createdNodes[$nodeData['slug']]->update([
                    'prerequisite_node_ids' => collect($nodeData['prerequisites'])
                        ->map(fn (string $slug): int => (int) $createdNodes[$slug]->id)
                        ->values()
                        ->all(),
                ]);

                $skills[$nodeData['skill']]->update([
                    'prerequisites' => [
                        'node_slugs' => $nodeData['prerequisites'],
                        'required_level' => $nodeData['required_level'],
                    ],
                ]);
            }
        }
    }

