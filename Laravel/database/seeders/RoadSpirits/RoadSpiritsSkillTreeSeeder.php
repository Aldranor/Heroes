    protected function animationKey(array $skillData): string
    {
        if (($skillData['slot_type'] ?? 'active') === 'passive') {
            return 'idle';
        }

        return match ($skillData['type']) {
            SkillType::Heal, SkillType::Buff, SkillType::ThemeBonus => 'cast',
            SkillType::Shield, SkillType::Defense, SkillType::PenaltyReduction => 'guard',
            SkillType::AreaAttack => 'slash',
            SkillType::Debuff => 'cast',
            default => (($skillData['range_type'] ?? null) === 'ranged' ? 'shoot' : 'attack'),
        };
    }
